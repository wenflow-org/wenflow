/**
 * 悬空「图/板」引用的识别与剥离（原在 teaching-visual.service.ts，2026-11-03 拆出）。
 *
 * 拆出的原因有两条，方向一致：
 * 1. 超大文件棘轮：`teaching-visual.service.ts` 已超基线且只许缩短，这段纯文本处理与出图主流程无关；
 * 2. 职责单一：这里只有"这句话是不是在指一张不存在的图"和"把它改成不指图的说法"，
 *    不依赖 SVG/图型/配额等出图状态。
 *
 * 调用方（teaching-turn-engine 的 D10 剥离、以及 teaching-visual.service 的再导出）签名不变。
 *
 * ## 改写口径：删，不要换（2026-11-03 真人走查之后的收口）
 *
 * 2026-11-03 中午这版把每个指代**替换**成一个中性名词短语（板上→「刚才的对比」、
 * 这张图→「下面的对比」）。真人走查的原句一过就露馅——替换进去的是一个**新的指代对象**，
 * 屏上根本没有那样东西，而且落点常常不成句：
 *
 * | 原句 | 替换版产出 |
 * | --- | --- |
 * | 板上这张图把「总迟到」拆成了两栏… | 刚才的对比把「总迟到」拆成了两栏…（"刚才的对比"是凭空多出来的东西）|
 * | 看这张对照图，左右两栏并排摆着了，你自己对一眼。| 下面的对比，左右刚才左右对照的两组，你自己对一眼。（读不通）|
 * | 再看板上两个圈。| 再看刚才的对比两个圈。（不成句）|
 *
 * 所以口径反过来：**宁可删掉指代那几个字，也不要换一个新名词进去**。
 * 删完若整条句子只剩标点，交给下面的空句清理；调用方按「剥离结果为空则不动原文」处理
 * （见 teaching-turn-engine：`if (stripped && stripped !== content)`）。
 *
 * 唯一保留"替换"的是**复用原句自身内容**的那条：「我把 X 画在图里了」→「我已经把 X 整理了一遍」——
 * 它把 X 从"图里的东西"改回"被整理的东西"，没有引入新对象，且保住了教学信息。
 */

/**
 * 指向「图」的显式引用（A/B 报告 D10，2026-10-13）：回复里出现"（见图）/（如下图）/我画了一个结构示意"
 * 这类指向本轮附图的指引，但消息实际不带任何图（images/diagrams/figures 全空）→ 学生看到的是一句指向虚空的话。
 *
 * 判据取紧（宁漏不误，只剥真悬空）：① 括号里的图指引（见图/如下图/详见下图…）；
 * ② 第一人称"我（给你）画了…图/示意"的落笔声称——只认"我…画了"，不碰祈使句
 * （"你可以画一张""自己画一条"是布置练习，不是声称已画）。
 */
const DANGLING_FIGURE_PARENTHETICAL = /[（(]\s*(?:详见|参见|见|如|如下图|见下图)?\s*(?:上|下|左|右|本)?图(?:示|解|表)?\s*[）)]/g;
const DANGLING_FIGURE_CLAIM = /我(?:给(?:你|您))?画(?:了|好|上)(?:[一二两三四五几]|张|幅|个)?[^，。；！？\n]{0,8}?(?:示意图|结构图|结构示意|示意图|图|示意)/g;
/**
 * 板书/课堂图指代（2026-10-28 真实课堂实测）：模型在没有图的回合里仍会说
 * 「这条链我摆成图了」「图上两个问号」「你照着图说一遍」。旧正则只认
 * 「（见图）」和「我画了…图」，拦不住这些变体，学生界面上就是对着空气喊看图。
 */
const DANGLING_FIGURE_DEIXIS =
  /(?:看|对|照|盯|按|比|顺着|沿着)(?:着|下|一下)?(?:上面|下面|左边|右边|这张|那张|刚才)?(?:图|箭头)|图(?:上|里|中)|(?:摆成|画成|做成|整理成)(?:了)?[^，。；！？\n]{0,6}图|箭头(?:上|里|中)?的?(?:字|方向)|两个问号|(?:下面|上面|下方|上方|如|见)?(?:这|那)(?:张|幅|个)?图(?:表|示)?|下(?:面|方)?图|如图(?:所示)?|白板|板上/;

/**
 * 「指代词 + 修饰语 + 图」的指代（2026-11-02 走查实锤）：上面 DANGLING_FIGURE_DEIXIS 里的
 * 「这张图」要求「这张」与「图」紧邻，而真实课堂文本是「看这张**对照**图」「那张**结构**图」——
 * 中间夹一个「对照/结构/关系/流程」整条就漏网，于是有图的字段被图闸丢掉、正文却留着指代，
 * 屏上就是对着空白处喊「看这张对照图」。黑体实测：整场 21 条消息 figures/diagrams 全为 0，
 * 正文仍写「看这张对照图，左右两栏并排摆着了」，剥离一次都没触发。
 * 只补这一类（量词做锚）。不碰无修饰的「左右两列」——markdown 表格真的有列，剥了反而说错。
 */
const DANGLING_FIGURE_DEIXIS_MODIFIED =
  /(?:这|那)(?:张|幅|个|块)[^，。；！？\n]{0,4}?图(?:表|示)?/;

/**
 * 待删除的指代片段，**长的在前**（否则「这张对照图」会被「这张图」先啃掉半截）。
 * 每条都只删"指向图的那一小截"，让句子剩下的部分自己成句。
 * 末尾带 `[，,]?` 的：连它后面那个逗号一起删，免得留下「，左右两栏…」这种悬空逗号。
 */
const DANGLING_FIGURE_DELETIONS: RegExp[] = [
  // 括注（见图）/（如下图）——删括注本身。
  DANGLING_FIGURE_PARENTHETICAL,
  // 「图（已经）放到板上了」整段声称——不整段删会留下「图已经放到了」这种残句。
  /(?:图)?(?:已经)?(?:放到|摆到|画到|画上|放上|摆上|移到)板上了?[—\-，,]*/g,
  // 「（看）这张对照图（里/上/中）把/将」——指代在主语位置时，连前面的把/将字标记与后面的
  // 把字句标记一起删，否则留下「把「总迟到」拆成了两栏」这种没有主语的残句，
  // 或「为了帮你把这张图看得更清楚」这种删剩一个孤零零「把」的半句。
  /(?:把|将)?(?:看|瞧|瞅|盯|对着|照着|按着)?(?:下面|上面|左边|右边|下方|上方)?(?:这|那)(?:张|幅|个|块)[^，。；！？\n]{0,4}?图(?:表|示)?(?:里|上|中)?(?:就是)?[，,、]?\s*(?:把|将)?/g,
  // 「图上/图里/图中（的）」——指代单独出现时的兜底（放在上面两条之后：它们要先啃掉带修饰语的长形态）。
  /图(?:上|里|中)(?:的)?/g,
  // 「你照着图，」——带主语的祈使指代整小句删（连后随逗号），免得留下「你，用自己…」。
  /(?:你|请您|咱们)(?:直接)?(?:看图|瞧着图|看这张|照着图|看着图|对着图)[，,]?/g,
  // 「（直接）看图」——不带主语时只删指代本身、**留下逗号**，否则「三处的先后看图，你只需…」
  // 会变成「三处的先后你只需…」，两个小句粘在一起。
  /(?:直接)?(?:看图|瞧着图|看这张|照着图|看着图|对着图)/g,
  // 「（对着）箭头（上的字/方向）」
  /(?:对着|照着|看着|按着|顺着|沿着|盯着)?箭头(?:上|里|中)?的?(?:字|方向|指示)?/g,
  // 「白板上 / 板上」（「白板上」在「白板」之前，否则白板先被吃掉只剩一个「上」）
  /白板上|白板|板上/g,
  // 「下（面/方）图 / 如图（所示）」
  /下(?:面|方)?图|如图(?:所示)?/g,
  // 「左右两栏并排摆着了」——这是对一块**不存在的板**的排布断言，整段删（不是指代，也不是内容）。
  // 「左右」可选前缀必须包含在匹配里，否则只剩一个孤零零的「左右」。
  /(?:左右)?(?:两|两栏)(?:栏)?(?:并排)?(?:摆|放)着(?:了)?[，,]?/g,
  // 「（把）X 摆成/画成/做成/整理成（了）图（里/上/中）（了）」——落笔声称的整段；
  // 放在「我把 X 画在图里」那条之前，先吃掉没有对象的变体（「这条链我摆成图了」）。
  /(?:这条|这个|这)?(?:链|关系|结构|东西|内容)?我(?:已经)?(?:给你|您)?[^，。；！？\n]{0,10}?(?:摆成|画成|做成|整理成)(?:了)?[^，。；！？\n]{0,6}?图(?:里|上|中)?(?:了)?[，,]?/g,
];

/**
 * 唯一保留的"改写"：把 X 从"图里的东西"改回"被整理的东西"（复用原句自身内容，不引入新对象）。
 * 2026-10-29 真 LLM 实测变体：「我把两条对比画在图里了，你先只看一眼：它们 b 一样…」——
 * 删掉整句会连「两条对比」这个对比对象一起丢掉，所以这里替换而不是删除。
 */
const DANGLING_FIGURE_MOVES: Array<[RegExp, string]> = [
  [/我(?:已经)?把([^，。；！？\n]{0,12}?)(?:画|摆|放|做|整理)(?:在|到|成)(?:了)?[^，。；！？\n]{0,6}?图(?:里|上|中)?(?:了)?/g, '我已经把$1整理了一遍'],
];

/** 回复里是否存在指向「本轮并不存在的图」的悬空引用。 */
export function hasDanglingFigureReference(reply: string | null | undefined): boolean {
  const text = String(reply ?? '');
  if (!text) return false;
  DANGLING_FIGURE_PARENTHETICAL.lastIndex = 0;
  DANGLING_FIGURE_CLAIM.lastIndex = 0;
  return DANGLING_FIGURE_PARENTHETICAL.test(text)
    || DANGLING_FIGURE_CLAIM.test(text)
    || DANGLING_FIGURE_DEIXIS.test(text)
    || DANGLING_FIGURE_DEIXIS_MODIFIED.test(text);
}

/**
 * 剥离指向「不存在的图」的悬空引用：删除指代片段 + 清理删完留下的空标点/空句。
 * 仅在消息确认不带图时调用（见 teaching-turn-engine 调用点）。
 *
 * 不承诺"内容无损"：本轮无图时，模型本来就不该写依赖图的句子（提示词明文要求 reply 纯文本自足）。
 * 这里只保证删完**读得通**——剩下的句子是完整的，且不出现任何**新的指代对象**。
 */
export function stripDanglingFigureReferences(reply: string | null | undefined): string {
  const text = String(reply ?? '');
  if (!text) return text;
  let out = text.replace(DANGLING_FIGURE_CLAIM, '');
  // 先跑「复用原句内容」的改写：它会用到「画在…图里」这个完整形态，
  // 若先跑删除，「图里」已被吃掉，只剩「我把两条对比画在了」。
  for (const [pattern, replacement] of DANGLING_FIGURE_MOVES) {
    out = out.replace(pattern, replacement);
  }
  for (const pattern of DANGLING_FIGURE_DELETIONS) {
    out = out.replace(pattern, '');
  }
  return out
    // 删掉指代后留下的空标点：连续标点只留一个、标点前的空白去掉、行首/句首的孤立标点去掉。
    .replace(/\s+([，。；！？、：])/g, '$1')
    .replace(/([，。；！？、：])\1+/g, '$1')
    .replace(/[（(]\s*[）)]/g, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/(^|\n)\s*[，,、；;—\-]+\s*/g, '$1')
    .replace(/([。！？\n])\s*[，,、；;]\s*/g, '$1')
    .trim();
}
